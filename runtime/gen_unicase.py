#!/usr/bin/env python3
"""Writes runtime/unicase.c: the simple one-to-one Unicode case mappings the
runtime's String.toUpper / String.toLower apply (GAPS G36).

The rule is exactly the bootstrap's (bootstrap/antpy/library.py `case_map`):
a code point maps when Python's str.upper() / str.lower() of it is a single
code point that differs from it, and is left alone otherwise. Running this
once by hand, with the same Python the bootstrap runs under, keeps the
runtime and the bootstrap in agreement on every code point. Nothing in the
build or the runtime runs this script; the generated file is checked in.

    python3 -I runtime/gen_unicase.py         (from the repository root)
"""
import sys
import unicodedata
from pathlib import Path


def pairs(fn):
    out = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        m = fn(c)
        if len(m) == 1 and m != c:
            out.append((cp, ord(m)))
    return out


def table(name, rows):
    lines = ["static const uint32_t %s[][2] = {" % name]
    for i in range(0, len(rows), 8):
        chunk = rows[i:i + 8]
        lines.append("  " + " ".join("{0x%04X, 0x%04X}," % r for r in chunk))
    lines.append("};")
    return "\n".join(lines)


def main():
    root = Path(__file__).resolve().parents[1]
    upper = pairs(str.upper)
    lower = pairs(str.lower)
    header = (
        "/* GENERATED by runtime/gen_unicase.py with Python %s (Unicode %s); do not\n"
        " * edit by hand, regenerate. The simple one-to-one case mappings of\n"
        " * String.toUpper / String.toLower (GAPS G36): a code point maps when its\n"
        " * mapping is a single different code point, exactly the bootstrap's rule in\n"
        " * bootstrap/antpy/library.py case_map. UPPER has %d pairs, LOWER %d, both\n"
        " * sorted by code point. */\n"
        % (sys.version.split()[0], unicodedata.unidata_version, len(upper), len(lower))
    )
    body = """#include <stdint.h>
#include "ant.h"

%s

%s

/* The mapped code point, or cp itself when the table has no entry for it. */
static int32_t lookup(const uint32_t (*t)[2], int n, int32_t cp) {
  int lo = 0, hi = n - 1;
  while (lo <= hi) {
    int mid = lo + (hi - lo) / 2;
    if (t[mid][0] == (uint32_t)cp) return (int32_t)t[mid][1];
    if (t[mid][0] < (uint32_t)cp) lo = mid + 1; else hi = mid - 1;
  }
  return cp;
}

int32_t ant_cp_upper(int32_t cp) { return lookup(UPPER, ANT_LEN(UPPER), cp); }
int32_t ant_cp_lower(int32_t cp) { return lookup(LOWER, ANT_LEN(LOWER), cp); }
""" % (table("UPPER", upper), table("LOWER", lower))
    out = root / "runtime" / "unicase.c"
    out.write_text(header + body)
    print("wrote %s: %d upper, %d lower pairs" % (out, len(upper), len(lower)))


if __name__ == "__main__":
    main()
